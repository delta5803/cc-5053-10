#!/usr/bin/env node
// Offline parity report: runs the same engine rules as the GUI and verifies
// selection, sounding pitch, voice counts, loop seams, cache bounds and the
// voice-stealing policy. Writes report.json, rendered WAVs and a text summary.
//
// Usage: node tools/offline.mjs [--out docs/offline]
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  buildInstrument,
  describeKeyMap,
  selectSample,
  layerMixFor,
  zoneFor,
  analyzeLoop,
  estimatePitch,
  centsOff,
  sampleBytes,
  residentBytes,
  SampleCache,
  VoiceManager,
  OfflineRenderer,
  midiToHz,
  noteName,
  SamplerError,
  DEFAULTS,
} from '../src/engine.js';
import { decodeWav, encodeWav16 } from '../src/wav.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SAMPLES = join(ROOT, 'assets', 'samples');
const OUT = resolve(process.argv.includes('--out')
  ? process.argv[process.argv.indexOf('--out') + 1]
  : join(ROOT, 'docs', 'offline'));
mkdirSync(OUT, { recursive: true });
mkdirSync(join(OUT, 'audio'), { recursive: true });

const manifest = JSON.parse(readFileSync(join(SAMPLES, 'recordings.json'), 'utf8'));
const instrument = buildInstrument(manifest);
const pcmByKey = new Map();
for (const rec of manifest.notes) {
  const wav = decodeWav(readFileSync(join(SAMPLES, rec.file)));
  pcmByKey.set(rec.name, wav.pcm);
}
const sr = manifest.sampleRate;

const report = {
  generatedAt: new Date().toISOString(),
  source: {
    description: 'Original synthetic recordings generated by tools/generate-samples.mjs',
    recordings: manifest.notes.length,
    sampleRate: sr,
    totalSourceSeconds: +manifest.notes.reduce((s, r) => s + r.seconds, 0).toFixed(2),
    residentBytes: residentBytes(instrument),
    cacheBudgetBytes: instrument.cfg.cacheBytes,
  },
  keyMap: describeKeyMap(instrument),
  velocity: {
    blend: instrument.velocityBlend,
    table: [1, 2, 8, 20, 40, 63, 64, 75, 76, 84, 90, 99, 100, 110, 127].map((v) => {
      const mix = layerMixFor(v, instrument);
      const sel = selectSample(instrument, 60, v);
      return {
        velocity: v,
        kind: mix.kind,
        softWeight: +mix.soft.toFixed(4),
        hardWeight: +mix.hard.toFixed(4),
        amplitude: +sel.gain.toFixed(4),
        samples: sel.entries.map((e) => e.sample.name),
      };
    }),
  },
  selection: {},
  pitch: {},
  loops: {},
  voices: {},
  cache: {},
  determinism: {},
  errors: [],
  files: {},
};

// ---------------------------------------------------------------------------
// 1. Selection at zone boundaries and across the keyboard
// ---------------------------------------------------------------------------
{
  const rows = [];
  for (const z of instrument.zones) {
    const notes = [z.lo, z.lo + 1, z.rootMidi, z.hi - 1, z.hi].filter((n, i, a) => n >= 0 && a.indexOf(n) === i);
    for (const n of notes) {
      const sel = selectSample(instrument, n, 100);
      rows.push({
        note: n,
        noteName: noteName(n),
        zoneRoot: sel.zone.rootMidi,
        zoneRange: [sel.zone.lo, sel.zone.hi],
        semitones: sel.semitones,
        playbackRate: +sel.rate.toFixed(6),
        sample: sel.entries.map((e) => e.sample.name).join('+'),
        boundary: n === z.lo && z.index > 0,
        reason: sel.reason,
      });
    }
  }
  report.selection.boundaries = rows;
  report.selection.boundaryRule = 'ceiling midpoint toward the upper root; boundary note belongs to the lower zone';
}

// ---------------------------------------------------------------------------
// 2. Extreme-low velocity and blend continuity
// ---------------------------------------------------------------------------
{
  const low = [1, 2, 3, 4].map((v) => {
    const sel = selectSample(instrument, 60, v);
    const r = renderSingle(60, v, 1.0, null);
    return {
      velocity: v,
      layer: sel.mix.kind,
      amplitude: +sel.gain.toFixed(5),
      peak: +peakOf(r).toFixed(5),
      audible: peakOf(r) > 1e-4,
      samples: sel.entries.map((e) => e.sample.name),
    };
  });
  report.velocity.extremeLow = low;
  // Determinism: repeated identical input must pick the same samples.
  const samples = new Set();
  for (let i = 0; i < 200; i++) {
    const n = 48 + (i % 25);
    const v = 40 + (i % 50);
    samples.add(`${n}/${v}:` + selectSample(instrument, n, v).entries.map((e) => e.sample.name).join('+'));
  }
  const again = new Set();
  for (let i = 0; i < 200; i++) {
    const n = 48 + (i % 25);
    const v = 40 + (i % 50);
    again.add(`${n}/${v}:` + selectSample(instrument, n, v).entries.map((e) => e.sample.name).join('+'));
  }
  report.determinism.sameInputSameSamples = [...samples].every((k) => again.has(k)) && samples.size === again.size;
  report.determinism.distinctInputs = samples.size;
  // Velocity sweep must never jump backwards in output level, and inside the
  // band both layers must be present.
  const sweep = [];
  for (let v = 1; v <= 127; v++) {
    const sel = selectSample(instrument, 60, v);
    const r = renderSingle(60, v, 0.9, null);
    sweep.push({ v, kind: sel.mix.kind, gain: sel.gain, peak: peakOf(r), layers: sel.entries.length });
  }
  const monotone = sweep.every((s, i) => i === 0 || s.peak >= sweep[i - 1].peak - 1e-3);
  report.velocity.sweep = {
    monotoneNonDecreasing: monotone,
    blendBand: [instrument.cfg.velocityBlendLo, instrument.cfg.velocityBlendHi],
    blendPoints: sweep.filter((s) => s.kind === 'blend').map((s) => s.v),
    blendAlwaysTwoLayers: sweep.filter((s) => s.kind === 'blend').every((s) => s.layers === 2),
  };
}

// ---------------------------------------------------------------------------
// 3. Pitch of rendered output vs input note
// ---------------------------------------------------------------------------
{
  const checks = [];
  const notes = [37, 48, 54, 59, 60, 66, 72, 78, 84, 90, 96, 100, 103].filter(
    (n) => n >= instrument.noteRange.lo && n <= instrument.noteRange.hi,
  );
  let worst = 0;
  for (const n of notes) {
    for (const v of [20, 110]) {
      const sel = selectSample(instrument, n, v);
      const r = renderSingle(n, v, 1.25, null);
      // Measure in the steady part of the (looping) note.
      const p = estimatePitch(r.pcm, sr, { from: 0.22, to: 0.62, minHz: 25, maxHz: 5000 });
      const expected = midiToHz(n);
      const cents = p ? centsOff(p.hz, expected) : null;
      if (cents !== null) worst = Math.max(worst, Math.abs(cents));
      checks.push({
        note: n,
        noteName: noteName(n),
        velocity: v,
        sample: sel.entries.map((e) => e.sample.name).join('+'),
        playbackRate: +sel.rate.toFixed(6),
        expectedHz: +expected.toFixed(2),
        measuredHz: p ? +p.hz.toFixed(2) : null,
        cents: cents === null ? null : +cents.toFixed(1),
        confidence: p ? +p.confidence.toFixed(3) : null,
        ok: cents !== null && Math.abs(cents) <= 12,
      });
    }
  }
  report.pitch.checks = checks;
  report.pitch.worstCents = +worst.toFixed(1);
  report.pitch.allWithin12Cents = checks.every((c) => c.ok);
}

// ---------------------------------------------------------------------------
// 4. Loop seam checks (per recording, plus a long sustained render)
// ---------------------------------------------------------------------------
{
  const rows = [];
  for (const rec of manifest.notes) {
    const pcm = pcmByKey.get(rec.name);
    const a = analyzeLoop(rec, pcm, instrument.cfg);
    rows.push({ name: rec.name, ...a });
    if (rec.loop) {
      // Render a note held far longer than the recording and confirm the
      // output stays periodic at the seam (no visible click jump).
      const n = rec.rootMidi;
      const held = renderHeldRoot(rec.rootMidi, rec.layer === 'hard' ? 110 : 40, 3.0);
      const seamMetric = heldSeamMetric(held, rec, sr);
      rows[rows.length - 1].heldRender = seamMetric;
    }
  }
  report.loops.recordings = rows;
  report.loops.allOk = rows.every((r) => r.ok && (!r.heldRender || r.heldRender.ok));
  // Detect repeated clicking: count jumps in the rendered sustain that exceed
  // a robust threshold derived from the signal's own step distribution.
  report.loops.click = clickScanOnLoopingRender();
}

// ---------------------------------------------------------------------------
// 5. Voice counts: polyphony, rapid repeats, stealing
// ---------------------------------------------------------------------------
{
  const cases = [];
  // A 12-note chord: all voices must be active simultaneously.
  const chordEvents = [];
  for (let i = 0; i < 12; i++) chordEvents.push({ type: 'on', note: 48 + i, velocity: 90, time: 0.05 });
  for (let i = 0; i < 12; i++) chordEvents.push({ type: 'off', note: 48 + i, time: 2.6 });
  const chord = render(chordEvents, 3.0);
  cases.push({
    name: '12-note chord',
    expectedActive: 12,
    measuredMaxActive: chord.maxActive,
    logicalMax: Math.max(...chord.voiceLog.map((l) => l.active)),
    ok: chord.maxActive === 12,
  });

  // Rapid repeated same-note hits must each allocate a real voice, then
  // release cleanly; total active never exceeds the cap.
  const rapidEvents = [];
  for (let i = 0; i < 20; i++) {
    rapidEvents.push({ type: 'on', note: 72, velocity: 100, time: 0.02 + i * 0.045 });
    rapidEvents.push({ type: 'off', note: 72, time: 0.02 + i * 0.045 + 0.03 });
  }
  const rapid = render(rapidEvents, 4.0);
  const rapidOns = rapid.voiceLog.filter((l) => l.kind === 'noteOn').length;
  cases.push({
    name: '20 rapid repeats of C5',
    expectedOnEvents: 20,
    measuredOnEvents: rapidOns,
    maxActive: rapid.maxActive,
    overCap: rapid.maxActive > instrument.cfg.maxVoices,
    samplesUsed: [...new Set(rapid.voiceLog.filter((l) => l.kind === 'noteOn').flatMap((l) => l.samples))],
    layerMixes: [...new Set(rapid.voiceLog.filter((l) => l.kind === 'noteOn').map((l) => l.layers.join('+')))],
    ok: rapidOns === 20 && rapid.maxActive <= instrument.cfg.maxVoices && rapid.maxActive >= 2,
  });

  // Stealing: request more notes than the cap and confirm the count is held.
  const capTest = renderChordWithCap(instrument.cfg.maxVoices + 8, instrument.cfg.maxVoices);
  cases.push({
    name: `steal beyond cap ${instrument.cfg.maxVoices}`,
    requested: instrument.cfg.maxVoices + 8,
    measuredMaxActive: capTest.maxActive,
    steals: capTest.steals,
    policy: 'oldest releasing voice first, else oldest held voice; stolen voice fades 8 ms and keeps its pin',
    ok: capTest.maxActive === instrument.cfg.maxVoices && capTest.steals >= 8,
  });

  report.voices.cases = cases;
  report.voices.allOk = cases.every((c) => c.ok);
  report.voices.maxVoices = instrument.cfg.maxVoices;
}

// ---------------------------------------------------------------------------
// 5b. Pedal retrigger: soft attack then hard attack on one pitch, key-up,
// pedal-up, and a late old-sample read callback. The old release must end only
// its own key instance; the pedal must own the released sounds as a set; the
// retriggered sound must survive. Read heads are aligned with the cache-unpin
// moments so a fix for one voice cannot free a buffer another still reads.
// ---------------------------------------------------------------------------
{
  const softNote = 60;
  const softVel = 40;
  const hardVel = 110;
  const softSel = selectSample(instrument, softNote, softVel);
  const hardSel = selectSample(instrument, softNote, hardVel);
  // Two visibly different recordings: the same pitch, different velocity
  // layers. Confirm they really are distinct buffers and different levels.
  const softBuf = pcmByKey.get(softSel.entries[0].sample.name);
  const hardBuf = pcmByKey.get(hardSel.entries[0].sample.name);
  const softRms = rmsOf(softBuf);
  const hardRms = rmsOf(hardBuf);
  // 180 ms key-up gap, pedal raised after the key-up, then a late callback.
  const tOn1 = 0.05;
  const tOn2 = 0.28;
  const tOff1 = 0.34; // first key released, pedal still down
  const tPedalUp = 0.55;
  const tLate = 0.80; // old sample's released read head would have ended here
  const events = [
    { type: 'pedal', down: true, time: 0.02 },
    { type: 'on', note: softNote, velocity: softVel, time: tOn1, tag: 'soft-hit' },
    { type: 'on', note: softNote, velocity: hardVel, time: tOn2, tag: 'hard-hit' },
    { type: 'off', note: softNote, time: tOff1, tag: 'soft-hit' },
    { type: 'pedal', down: false, time: tPedalUp },
    { type: 'off', note: softNote, time: tLate, tag: 'hard-hit' },
  ];
  const r = render(events, 2.4);
  const ons = r.voiceLog.filter((l) => l.kind === 'noteOn');
  const softOn = ons.find((l) => l.tag === 'soft-hit');
  const hardOn = ons.find((l) => l.tag === 'hard-hit');
  // The two attacks must use different, audibly different recordings.
  const distinctSamples = softSel.entries[0].sample.name !== hardSel.entries[0].sample.name;
  const levelDifference = Math.abs(20 * Math.log10(hardRms / Math.max(softRms, 1e-9)));
  // Each attack is a separate key instance with its own head and its own voice.
  const instancesDistinct = !!softOn && !!hardOn && softOn.id !== hardOn.id && softOn.instance !== hardOn.instance;
  const headsDistinct = !!softOn && !!hardOn && softOn.head !== hardOn.head;
  // The first (soft) instance must go to the pedal, not fade, while the second
  // (hard) instance is still held, then still sound until pedal-up.
  const softPedalHold = r.voiceLog.some((l) => l.kind === 'pedalHold' && l.id === softOn?.id);
  const softPedalRelease = r.voiceLog.some((l) => l.kind === 'pedalUpRelease' && l.id === softOn?.id);
  // The second sound is never terminated by the first key's release: the first
  // instance's note-off is a pedal hold, and the hard instance stays held until
  // its own key-up much later.
  const hardGotNoteOffBeforeItsOwnKeyUp = r.voiceLog.some(
    (l) => l.kind === 'noteOff' && l.id === hardOn?.id && l.time < tLate - 1e-6,
  );
  const hardStillSoundingAtOldTail = headActiveAt(r.heads, hardOn?.head, tLate - 0.02);
  // Measure each attack and each release tail directly in the mix around its
  // own onset, so the two sounds are separated in the final output.
  const attack1 = windowPeak(r.pcm, sr, tOn1, 0.06);
  const attack2 = windowPeak(r.pcm, sr, tOn2, 0.06);
  const tailSoft = windowPeak(r.pcm, sr, tPedalUp + 0.02, cfgRelease(instrument));
  const tailHard = windowPeak(r.pcm, sr, tLate + 0.02, cfgRelease(instrument));
  const bothAttacksAudible = attack1 > 0.01 && attack2 > 0.01;
  const softTailAudible = tailSoft > 0.005;
  const hardTailAudible = tailHard > 0.005;
  // "Clearly different" samples: different recordings *and* an audibly
  // different attack level in the final mix.
  const attackLevelDb = Math.abs(20 * Math.log10(attack2 / Math.max(attack1, 1e-9)));
  // Read heads: the soft head must be released at pedal-up, not at the key-up
  // (which is earlier) and not before the hard head's attack begins.
  const softHead = r.heads.find((h) => h.head === softOn?.head);
  const hardHead = r.heads.find((h) => h.head === hardOn?.head);
  const softReleasedAtPedal = softHead && Math.abs((softHead.releaseAt ?? -1) - tPedalUp) < 0.02;
  const headsOverlap = softHead && hardHead && softHead.end >= hardHead.start;
  // Cache ownership: unpinning the soft buffer at pedal-up+release must not
  // drop the hard voice's pin (two different recordings here, so both are
  // resident; the important part is refcounts returning to zero only at the
  // end). Capture the pin count of each recording while both sound.
  const cachePinsWhileBoth = cachePinsAt(r, [tOn2 + 0.05], [
    softSel.entries[0].sample.name,
    hardSel.entries[0].sample.name,
  ]);
  const pinsOk = cachePinsWhileBoth.every((p) => p.pins === 1 && p.headsAlive === 1);
  const unpinAuditSoftHard = unpinAudit(r, [
    softSel.entries[0].sample.name,
    hardSel.entries[0].sample.name,
  ]);
  const noPrematureFree = unpinAuditSoftHard.every((u) => !u.prematureFree);

  report.pedalRetrigger = {
    scenario: 'soft attack, then hard attack on the same pitch, key-up, pedal-up, late old read callback',
    schedule: { tOn1, tOn2, tOff1, tPedalUp, tLate },
    samples: {
      soft: { name: softSel.entries[0].sample.name, velocity: softVel, rms: +softRms.toFixed(4) },
      hard: { name: hardSel.entries[0].sample.name, velocity: hardVel, rms: +hardRms.toFixed(4) },
      distinctSamples,
      levelDifferenceDb: +levelDifference.toFixed(1),
      attackLevelDifferenceDb: +attackLevelDb.toFixed(1),
      distinct: distinctSamples && attackLevelDb > 3,
    },
    instances: {
      soft: softOn ? { id: softOn.id, instance: softOn.instance, head: softOn.head } : null,
      hard: hardOn ? { id: hardOn.id, instance: hardOn.instance, head: hardOn.head } : null,
      distinctInstances: instancesDistinct,
      distinctHeads: headsDistinct,
    },
    ownership: {
      softHeldByPedalAfterKeyUp: softPedalHold,
      softReleasedOnPedalUp: softPedalRelease,
      hardNotReleasedByFirstKeyUp: !hardGotNoteOffBeforeItsOwnKeyUp,
      hardStillSoundingBeforeLateCallback: hardStillSoundingAtOldTail,
      rule: 'note-off follows the key instance; the pedal owns the set of already-released instances',
    },
    mix: {
      attack1Peak: +attack1.toFixed(4),
      attack2Peak: +attack2.toFixed(4),
      softTailPeak: +tailSoft.toFixed(4),
      hardTailPeak: +tailHard.toFixed(4),
      bothAttacksAudible,
      softTailAudible,
      hardTailAudible,
    },
    readHeads: {
      soft: softHead ? { releaseAt: round4(softHead.releaseAt), end: round4(softHead.end), reason: softHead.releaseReason } : null,
      hard: hardHead ? { releaseAt: round4(hardHead.releaseAt), end: round4(hardHead.end), reason: hardHead.releaseReason } : null,
      softReleasedAtPedalUp: !!softReleasedAtPedal,
      headsOverlap: !!headsOverlap,
    },
    cache: {
      pinsWhileBothSound: cachePinsWhileBoth,
      unpinAudit: unpinAuditSoftHard,
      refsReturnToZero: pinsOk,
      noPrematureFree,
    },
    ok:
      distinctSamples && attackLevelDb > 3 &&
      instancesDistinct && headsDistinct &&
      softPedalHold && softPedalRelease && !hardGotNoteOffBeforeItsOwnKeyUp &&
      hardStillSoundingAtOldTail &&
      bothAttacksAudible && softTailAudible && hardTailAudible &&
      !!softReleasedAtPedal && !!headsOverlap &&
      pinsOk && noPrematureFree,
  };
}

// ---------------------------------------------------------------------------
// 5c. One free voice: the same reprise must either steal the old pedal tail
// (interrupt it) or let it finish naturally, and in both cases the two sample
// read heads must be handed back to the cache at moments matching the actual
// overlap, without freeing a recording still in use.
// ---------------------------------------------------------------------------
{
  const note = 60;
  const cases = [];

  // (a) Only one free voice, the old pedal tail is interrupted by the new
  // attack: the new sound must win, the old head must fade within the steal
  // tail, and each recording must be pinned exactly once while it sounds.
  {
    const events = [
      { type: 'pedal', down: true, time: 0.02 },
      { type: 'on', note, velocity: 40, time: 0.05, tag: 'old-soft' },
      { type: 'off', note, time: 0.20, tag: 'old-soft' },
      { type: 'on', note, velocity: 110, time: 0.30, tag: 'new-hard' },
      { type: 'pedal', down: false, time: 0.60 },
      { type: 'off', note, time: 0.75, tag: 'new-hard' },
    ];
    const rr = new OfflineRenderer(instrument, pcmByKey, { maxVoices: 1 }).render(events, { seconds: 1.6 });
    const steal = rr.voiceLog.find((l) => l.kind === 'steal');
    const newOn = rr.voiceLog.find((l) => l.kind === 'noteOn' && l.tag === 'new-hard');
    const newAlive = headActiveAt(rr.heads, newOn?.head, 0.32);
    const stealTailSec = instrument.cfg.stealReleaseMs / 1000;
    const oldInterrupted = rr.heads.some((h) => h.stolenAt !== null);
    const oldHeadEndedSoon = rr.heads.some((h) => h.stolenAt !== null && h.end - h.stolenAt <= stealTailSec + 0.01);
    const bothRecordingsPinnedOnce = cachePinsAt(rr, [0.34], [
      selectSample(instrument, note, 40).entries[0].sample.name,
      selectSample(instrument, note, 110).entries[0].sample.name,
    ]);
    // With one voice the old head is faded by the steal; after the fade only
    // the new recording may remain pinned, and the old one must be released
    // exactly when its head ends (not before).
    const oldKey = selectSample(instrument, note, 40).entries[0].sample.name;
    const newKey = selectSample(instrument, note, 110).entries[0].sample.name;
    const afterFade = cachePinsAt(rr, [0.36], [oldKey, newKey]);
    const oldRefReleasedAfterFade = afterFade.find((p) => p.key === oldKey)?.pins === 0;
    const newStillPinned = afterFade.find((p) => p.key === newKey)?.pins === 1;
    const audit = unpinAudit(rr, [oldKey, newKey]);
    const noPrematureFree = audit.every((u) => !u.prematureFree);
    cases.push({
      name: 'one free voice: new attack steals the old pedal tail',
      maxVoices: 1,
      maxActive: rr.maxActive,
      maxAudible: rr.maxAudible,
      steals: rr.voiceManager.steals,
      oldTailInterrupted: oldInterrupted,
      oldTailFadeSeconds: oldHeadEndedSoon ? +(stealTailSec).toFixed(3) : null,
      newSoundSurvives: !!newAlive,
      pinsWhileBothSound: bothRecordingsPinnedOnce,
      pinsAfterStealFade: afterFade,
      oldRefReleasedAfterFade,
      newStillPinned,
      unpinAudit: audit,
      headTrace: rr.heads.map((h) => ({
        head: h.head, voiceId: h.voiceId, note: h.note, velocity: h.velocity,
        start: round4(h.start), releaseAt: round4(h.releaseAt), stolenAt: round4(h.stolenAt), end: round4(h.end),
      })),
      ok:
        rr.maxActive === 1 && !!steal && !!newAlive && oldInterrupted && oldHeadEndedSoon &&
        oldRefReleasedAfterFade && newStillPinned && noPrematureFree,
    });
  }

  // (b) Only one free voice, but the new attack comes after the old pedal tail
  // has naturally finished: no steal is needed and the old recording may be
  // reused for the new sound without either read head being freed early.
  {
    const releaseSec = instrument.cfg.releaseMs / 1000;
    const tOff = 0.20;
    const tPedalUp = 0.30;
    const oldDone = tPedalUp + releaseSec + 0.02;
    const tNew = oldDone + 0.05;
    const events = [
      { type: 'pedal', down: true, time: 0.02 },
      { type: 'on', note, velocity: 40, time: 0.05, tag: 'old-soft' },
      { type: 'off', note, time: tOff, tag: 'old-soft' },
      { type: 'pedal', down: false, time: tPedalUp },
      { type: 'on', note, velocity: 110, time: tNew, tag: 'new-hard' },
      { type: 'off', note, time: tNew + 0.25, tag: 'new-hard' },
    ];
    const rr = new OfflineRenderer(instrument, pcmByKey, { maxVoices: 1 }).render(events, { seconds: 1.6 });
    const ons = rr.voiceLog.filter((l) => l.kind === 'noteOn');
    const steals = rr.voiceManager.steals;
    const oldHead = rr.heads.find((h) => h.velocity === 40);
    const newHead = rr.heads.find((h) => h.velocity === 110);
    const oldFinishedFirst = oldHead && newHead && oldHead.end <= newHead.start + 1e-6;
    const noSteal = steals === 0;
    // Both heads get their own pin and hand it back once; since the soft and
    // hard recordings differ, sharing is not required, but refcounts must hit
    // zero only after each head ends.
    const finalPins = [selectSample(instrument, note, 40).entries[0].sample.name,
      selectSample(instrument, note, 110).entries[0].sample.name]
      .map((k) => ({ key: k, pins: rr.cache.entries.get(k)?.pins ?? 0 }));
    const refsCleared = finalPins.every((p) => p.pins === 0);
    const audit = unpinAudit(rr, finalPins.map((p) => p.key));
    const noPrematureFree = audit.every((u) => !u.prematureFree);
    cases.push({
      name: 'one free voice: old pedal tail finishes naturally first',
      maxVoices: 1,
      maxActive: rr.maxActive,
      steals,
      oldHeadEndsBeforeNewStarts: !!oldFinishedFirst,
      pinsAtEnd: finalPins,
      refsCleared,
      unpinAudit: audit,
      headTrace: rr.heads.map((h) => ({
        head: h.head, voiceId: h.voiceId, note: h.note, velocity: h.velocity,
        start: round4(h.start), releaseAt: round4(h.releaseAt), stolenAt: round4(h.stolenAt), end: round4(h.end),
      })),
      ok: ons.length === 2 && noSteal && rr.maxActive === 1 && !!oldFinishedFirst && refsCleared && noPrematureFree,
    });
  }

  report.pedalOneFreeVoice = {
    cases,
    allOk: cases.every((c) => c.ok),
    note:
      'with one free voice the reprise either steals the pedal-held tail (8 ms fade) or waits for it to end; ' +
      'read-head unpins match the actual overlap and never free a recording another head is reading',
  };
}

// ---------------------------------------------------------------------------
// 6. Cache bounds and pin protection
// ---------------------------------------------------------------------------
{
  const cases = [];
  const full = residentBytes(instrument);
  // (a) Budget below a single recording must be rejected with a clear code.
  const tiny = new SampleCache(instrument, { cacheBytes: 1024 });
  const rec = manifest.notes[0];
  try {
    tiny.put(rec.name, pcmByKey.get(rec.name));
    cases.push({ name: 'budget smaller than one sample', ok: false, note: 'expected rejection but load succeeded' });
  } catch (err) {
    cases.push({
      name: 'budget smaller than one sample',
      ok: err instanceof SamplerError && err.code === 'CACHE_TOO_SMALL',
      code: err.code,
      message: err.message,
      hint: err.hint,
    });
  }

  // (b) Budget that fits only two recordings: loads evict LRU unpinned entries
  // and never exceed the budget.
  const twoRecs = sampleBytes(manifest.notes[0]) + sampleBytes(manifest.notes[1]);
  const small = new SampleCache(instrument, { cacheBytes: twoRecs + Math.floor(sampleBytes(manifest.notes[0]) / 2) });
  for (const r of manifest.notes.slice(0, 4)) small.put(r.name, pcmByKey.get(r.name));
  cases.push({
    name: 'LRU eviction under budget',
    budget: small.budget,
    used: small.usedBytes,
    evictions: small.evictions,
    withinBudget: small.usedBytes <= small.budget && small.peakBytes <= small.budget,
    ok: small.evictions > 0 && small.usedBytes <= small.budget && small.peakBytes <= small.budget,
  });

  // (c) Both recordings are held by sounding voices (pinned). A third load
  // must be refused with CACHE_PINNED_FULL, and both pinned recordings must
  // still be resident afterwards (the unpinned one may be evicted instead,
  // which is correct, so this test pins both).
  const bySize = [...manifest.notes].sort((a, b) => sampleBytes(b) - sampleBytes(a));
  const pair = [bySize[0], bySize[1]];
  const third = manifest.notes.find((r) => !pair.includes(r));
  const pinnedBudget = sampleBytes(pair[0]) + sampleBytes(pair[1]);
  const pinnedStore = new SampleCache(instrument, { cacheBytes: pinnedBudget });
  pinnedStore.put(pair[0].name, pcmByKey.get(pair[0].name));
  pinnedStore.pin(pair[0].name);
  pinnedStore.put(pair[1].name, pcmByKey.get(pair[1].name));
  pinnedStore.pin(pair[1].name);
  try {
    pinnedStore.put(third.name, pcmByKey.get(third.name));
    cases.push({ name: 'pinned sample protection', ok: false, note: 'expected CACHE_PINNED_FULL' });
  } catch (err) {
    cases.push({
      name: 'pinned sample protection',
      ok:
        err instanceof SamplerError &&
        err.code === 'CACHE_PINNED_FULL' &&
        pinnedStore.has(pair[0].name) &&
        pinnedStore.has(pair[1].name),
      code: err.code,
      message: err.message,
      hint: err.hint,
      stillResident: pinnedStore.snapshot().entries.map((e) => e.key),
    });
  }
  pinnedStore.unpin(pair[0].name);
  pinnedStore.unpin(pair[1].name);

  // (d) Voice pins track the voice lifecycle: unpin only when the voice ends.
  const store = new SampleCache(instrument, { cacheBytes: full });
  for (const r of manifest.notes) store.put(r.name, pcmByKey.get(r.name));
  const vm = new VoiceManager(instrument, store);
  const on = vm.noteOn(60, 100, 0);
  const pinsDuringVoice = store.get(on.plan.entries[0].sample.name).pins;
  vm.noteOff(60, 0.5);
  vm.tick(1.0);
  const pinsAfter = store.get(on.plan.entries[0].sample.name)?.pins ?? 0;
  cases.push({
    name: 'voice holds pin while sounding',
    pinsDuringVoice,
    pinsAfterFinish: pinsAfter,
    ok: pinsDuringVoice >= 1 && pinsAfter === 0 && !store.has(on.plan.entries[0].sample.name) === false,
  });
  report.cache = {
    residentBytes: full,
    budget: instrument.cfg.cacheBytes,
    recordingsResident: manifest.notes.length,
    cases,
    allOk: cases.every((c) => c.ok),
    policy:
      'LRU eviction of unpinned entries only; samples held by active voices (including steal tails) are never unloaded; ' +
      'an over-budget request fails with CACHE_PINNED_FULL rather than dropping audio',
  };
}

