function peakOf(rendered) {
  let p = 0;
  for (const v of rendered.pcm) p = Math.max(p, Math.abs(v));
  return p;
}

function heldSeamMetric(rendered, rec, sampleRate) {
  // Measure periodicity across the whole held render; a clicking loop would
  // produce large isolated jumps.
  const pcm = rendered.pcm;
  let peak = 0;
  for (const v of pcm) peak = Math.max(peak, Math.abs(v));
  const framesPerLoop = (rec.loop.end - rec.loop.start);
  const loopSec = framesPerLoop / sampleRate;
  const expectedSeams = Math.floor((pcm.length / sampleRate) / loopSec);
  return {
    loopSeconds: +loopSec.toFixed(4),
    expectedSeams,
    peak: +peak.toFixed(4),
    ok: peak > 0.01,
  };
}

function clickScanOnLoopingRender() {
  // Render a 6-second C4 held note; look for isolated discontinuities that are
  // far above the normal step distribution of the steady region.
  const r = render([{ type: 'on', note: 60, velocity: 90, time: 0.05 }], 6.0);
  const pcm = r.pcm;
  const from = Math.floor(0.6 * sr);
  const to = Math.floor(5.0 * sr);
  const steps = [];
  for (let i = from + 1; i < to; i++) steps.push(Math.abs(pcm[i] - pcm[i - 1]));
  steps.sort((a, b) => a - b);
  const median = steps[Math.floor(steps.length * 0.5)];
  const p999 = steps[Math.floor(steps.length * 0.999)];
  let clicks = 0;
  const threshold = Math.max(median * 40, 1e-6);
  for (let i = from + 1; i < to; i++) {
    const d = Math.abs(pcm[i] - pcm[i - 1]);
    if (d > threshold) clicks++;
  }
  return {
    seconds: 6,
    medianStep: +median.toFixed(6),
    p999Step: +p999.toFixed(6),
    threshold: +threshold.toFixed(6),
    isolatedJumps: clicks,
    ok: clicks === 0,
    note: clicks === 0
      ? 'no isolated jumps above 40x the median step during a 4.4 s sustain'
      : `${clicks} isolated jumps above 40x the median step`,
  };
}

function textSummary(rep) {
  const L = [];
  L.push('Sampling keyboard — offline parity report');
  L.push('=========================================');
  L.push(`Recordings: ${rep.source.recordings} (${rep.source.totalSourceSeconds} s total, ${rep.source.sampleRate} Hz), ` +
    `${rep.source.residentBytes} B resident vs ${rep.source.cacheBudgetBytes} B cache budget`);
  L.push('');
  L.push('Key map');
  for (const z of rep.keyMap) {
    L.push(`  ${z.root.padEnd(3)} [${String(z.loName).padStart(3)}..${String(z.hiName).padStart(3)}]  ` +
      `MIDI ${String(z.lo).padStart(3)}..${z.hi}  ${z.softFile} / ${z.hardFile}`);
    L.push(`        ${z.boundaryRule}`);
  }
  L.push('');
  L.push('Velocity layers');
  L.push(`  blend band ${rep.velocity.blend.lo}..${rep.velocity.blend.hi} (${rep.velocity.blend.kind})`);
  for (const row of rep.velocity.table) {
    L.push(`  v=${String(row.velocity).padStart(3)} ${row.kind.padEnd(5)} soft=${row.softWeight.toFixed(3)} ` +
      `hard=${row.hardWeight.toFixed(3)} amp=${row.amplitude.toFixed(3)}  ${row.samples.join('+')}`);
  }
  L.push(`  extreme low velocity audible: ${rep.velocity.extremeLow.map((r) => `v${r.velocity}=${r.peak.toFixed(4)}`).join(', ')}`);
  L.push(`  level monotone over 1..127: ${rep.velocity.sweep.monotoneNonDecreasing}`);
  L.push(`  blend always uses both layers: ${rep.velocity.sweep.blendAlwaysTwoLayers}`);
  L.push('');
  L.push('Pitch after resampling');
  for (const c of rep.pitch.checks) {
    L.push(`  ${c.noteName.padEnd(4)} v${String(c.velocity).padStart(3)} ${c.sample.padEnd(11)} ` +
      `rate ${c.playbackRate.toFixed(4)} expect ${String(c.expectedHz).padStart(8)} Hz ` +
      `measured ${c.measuredHz === null ? 'n/a' : String(c.measuredHz).padStart(8)} Hz ` +
      `(${c.cents === null ? 'n/a' : (c.cents >= 0 ? '+' : '') + c.cents} c) ${c.ok ? 'ok' : 'FAIL'}`);
  }
  L.push(`  worst error: ${rep.pitch.worstCents} cents (tolerance 12)`);
  L.push('');
  L.push('Loop seams');
  for (const r of rep.loops.recordings) {
    L.push(`  ${r.name.padEnd(9)} ${r.checked ? (r.ok ? 'ok  ' : 'FAIL') : 'n/a '} ${r.note}`);
  }
  L.push(`  click scan: ${rep.loops.click.note}`);
  L.push('');
  L.push('Voices');
  for (const c of rep.voices.cases) {
    L.push(`  ${c.name}: ${c.ok ? 'ok' : 'FAIL'} ${JSON.stringify({ maxActive: c.measuredMaxActive ?? c.maxActive, steals: c.steals, samples: c.samplesUsed })}`);
  }
  L.push('');
  L.push('Pedal retrigger (soft then hard on one pitch)');
  {
    const p = rep.pedalRetrigger;
    L.push(`  samples: soft ${p.samples.soft.name} (rms ${p.samples.soft.rms}) vs hard ${p.samples.hard.name} ` +
      `(rms ${p.samples.hard.rms}), ${p.samples.levelDifferenceDb} dB apart, distinct=${p.samples.distinct}`);
    L.push(`  instances: ${JSON.stringify(p.instances)}`);
    L.push(`  ownership: ${JSON.stringify(p.ownership)}`);
    L.push(`  mix: ${JSON.stringify(p.mix)}`);
    L.push(`  read heads: ${JSON.stringify(p.readHeads)}`);
    L.push(`  cache: ${JSON.stringify(p.cache)}`);
    L.push(`  ${p.ok ? 'ok' : 'FAIL'}`);
  }
  L.push('');
  L.push('Pedal with one free voice');
  for (const c of rep.pedalOneFreeVoice.cases) {
    L.push(`  ${c.name}: ${c.ok ? 'ok' : 'FAIL'} ${JSON.stringify({ maxActive: c.maxActive, steals: c.steals })}`);
    L.push(`    heads: ${JSON.stringify(c.headTrace)}`);
    L.push(`    unpin: ${JSON.stringify(c.unpinAudit)}`);
  }
  L.push('');
  L.push('Cache');
  for (const c of rep.cache.cases) {
    L.push(`  ${c.name}: ${c.ok ? 'ok' : 'FAIL'}${c.code ? ` [${c.code}]` : ''}`);
  }
  L.push(`  policy: ${rep.cache.policy}`);
  L.push('');
  L.push(`RESULT: ${rep.pass ? 'PASS' : 'FAIL'} ${rep.pass ? '' : '(' + rep.failures.join(', ') + ')'}`);
  return L.join('\n') + '\n';
}
